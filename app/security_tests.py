"""Test MQTT authentication, permissions and message delivery"""

import json
import os
from queue import Empty, Queue
from uuid import uuid4
import mqtt as mqtt
from app.model import GLO, make_event, topic_for


# connects to the MQTT broker using the specified account
def connect(username, password):
    responses = Queue()

    client = mqtt.Client(
        callback_api_version=mqtt.CallbackAPIVersion.VERSION2,
        client_id=f'test-{uuid4().hex[:12]}',
        protocol=mqtt.MQTTv5
    )

    client.username_pw_set(username, password)

    # records the broker connection response
    def on_connect(client, userdata, flags, reason, properties):
        responses.put(reason)

    client.on_connect = on_connect
    client.connect('broker', 1883)
    client.loop_start()

    try:
        reason = responses.get(timeout=8)
        return client, reason

    except Empty:
        client.disconnect()
        client.loop_stop()
        raise AssertionError('broker did not respond to the connection')


# publishes an event and checks broker acknowledgement
def publish(client, topic, event):
    responses = Queue()

    def on_publish(client, userdata, mid, reason, properties):
        responses.put((mid, reason))

    client.on_publish = on_publish

    info = client.publish(
        topic,
        json.dumps(event),
        qos=1
    )

    if info.rc != mqtt.MQTT_ERR_SUCCESS:
        raise AssertionError('the publish request failed')

    try:
        message_id, reason = responses.get(timeout=8)

    except Empty:
        raise AssertionError('broker did not acknowledge the message')

    if message_id != info.mid:
        raise AssertionError('unexpected publish acknowledgement')

    return reason


# reads a password generated by setup_demo.py
def password(username):
    return os.environ[f'MQTT_{username.upper()}_PASSWORD']


def test_invalid_password():
    """Check that the broker rejects an incorrect password"""

    client, reason = connect(
        'decant',
        password('decant') + '-wrong'
    )

    try:
        assert reason.is_failure, 'incorrect password was accepted'

    finally:
        client.disconnect()
        client.loop_stop()


def test_unauthorised_changes():
    """Check that decant cannot publish protected GLO updates"""

    client, reason = connect('decant', password('decant'))

    try:
        assert not reason.is_failure, 'decant could not connect'

        # tests all 3 types of protected production updates
        protected_events = (
            ('PRODUCTION_SCHEDULE_UPDATED', None),
            ('BATCH_CHANGE', 'decant'),
            ('PRODUCTION_RESUMED', 'elpo')
        )

        for event_type, department in protected_events:

            # simulates a department claiming to be a group leader
            event = make_event(
                GLO,
                event_type,
                department=department,
                issued_by='group_leader_1'
            )

            result = publish(
                client,
                topic_for(GLO, event_type, department),
                event
            )

            assert result.is_failure, (
                f'decant was allowed to publish {event_type}'
            )

    finally:
        client.disconnect()
        client.loop_stop()


def test_authorised_schedule():
    """Check that a group leader update reaches dispensary"""

    messages = Queue()
    subscriptions = Queue()

    subscriber, reason = connect(
        'dispensary',
        password('dispensary')
    )

    publisher = None

    try:
        assert not reason.is_failure, 'dispensary could not connect'

        # stores incoming production messages
        def on_message(client, userdata, message):
            messages.put(
                json.loads(message.payload.decode('utf-8'))
            )

        # records the subscription response
        def on_subscribe(client, userdata, mid, reasons, properties):
            subscriptions.put(reasons)

        subscriber.on_message = on_message
        subscriber.on_subscribe = on_subscribe

        subscriber.subscribe('factory/glo/schedule', qos=1)

        # confirms that the subscription was accepted
        try:
            reasons = subscriptions.get(timeout=8)

        except Empty:
            raise AssertionError('subscription timed out')

        assert all(
            not item.is_failure for item in reasons
        ), 'subscription was rejected'

        # connects using an authorised group leader account
        publisher, reason = connect(
            'group_leader_1',
            password('group_leader_1')
        )

        assert not reason.is_failure, 'group leader could not connect'

        # creates a simulated production schedule update
        event = make_event(
            GLO,
            'PRODUCTION_SCHEDULE_UPDATED',
            issued_by='group_leader_1',
            schedule='friday 09:00'
        )

        result = publish(
            publisher,
            topic_for(GLO, 'PRODUCTION_SCHEDULE_UPDATED'),
            event
        )

        assert not result.is_failure, 'schedule update was rejected'

        # confirms that dispensary received the correct event
        try:
            received = messages.get(timeout=8)

        except Empty:
            raise AssertionError('dispensary did not receive the update')

        assert received['event_id'] == event['event_id'], (
            'incorrect event received'
        )

    finally:
        # closes both MQTT connections
        if publisher is not None:
            publisher.disconnect()
            publisher.loop_stop()

        subscriber.disconnect()
        subscriber.loop_stop()


def main():
    """Run the security tests and display the results"""

    tests = (
        ('incorrect password rejected', test_invalid_password),
        ('unauthorised production changes rejected', test_unauthorised_changes),
        ('authorised schedule update received', test_authorised_schedule)
    )

    passed = 0

    for description, test in tests:
        try:
            test()
            print(f'PASS | {description}', flush=True)
            passed += 1

        except Exception as error:
            print(f'FAIL | {description} | {error}', flush=True)

    print(f'\nRESULT: {passed}/{len(tests)} PASSED', flush=True)

    if passed != len(tests):
        raise SystemExit(1)


if __name__ == '__main__':
    main()